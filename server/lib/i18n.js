export const STRINGS = { en, de, is };
export const normLang = l => (STRINGS[l] ? l : 'en');

export function t(lang, key, vars = {}) {
  const s = (STRINGS[lang] || en)[key] ?? en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] != null ? String(vars[k]) : `{${k}}`));
}
export const plural = (lang, n) => t(lang, n === 1 ? 'guests_one' : 'guests_other', { n });

const LOCALE = { en: 'en-GB', de: 'de-DE', is: 'is-IS' };
const fmtDate = (iso, lang) => new Intl.DateTimeFormat(LOCALE[lang] || 'en-GB', { weekday: 'long', day: 'numeric', month: 'long', timeZone: 'UTC' }).format(new Date(iso));
const fmtTime = iso => new Date(iso).toISOString().slice(11, 16);
export const when = (iso, lang) => `${fmtDate(iso, lang)} ${t(lang, 'at')} ${fmtTime(iso)}`;
export const day = (iso, lang) => fmtDate(iso, lang);
export const money = (n, lang) => `${new Intl.NumberFormat(LOCALE[lang] || 'en-GB', { maximumFractionDigits: 0 }).format(Math.round(n))} kr.`;
